CREATE TABLE pengumuman_kelas (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kelas_id INT UNSIGNED NOT NULL,
  penulis_id INT UNSIGNED NOT NULL,
  isi TEXT NOT NULL,
  dibuat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (kelas_id) REFERENCES kelas(id) ON DELETE CASCADE,
  FOREIGN KEY (penulis_id) REFERENCES pengguna(id)
) ENGINE=InnoDB;

CREATE TABLE tugas (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kelas_id INT UNSIGNED NOT NULL,
  judul VARCHAR(150) NOT NULL,
  deskripsi TEXT NULL,
  tenggat DATETIME NOT NULL,
  dibuat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (kelas_id) REFERENCES kelas(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE pengumpulan (
  tugas_id INT UNSIGNED NOT NULL,
  mahasiswa_id INT UNSIGNED NOT NULL,
  jawaban TEXT NOT NULL,
  dikirim DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (tugas_id, mahasiswa_id),
  FOREIGN KEY (tugas_id) REFERENCES tugas(id) ON DELETE CASCADE,
  FOREIGN KEY (mahasiswa_id) REFERENCES mahasiswa(pengguna_id) ON DELETE CASCADE
) ENGINE=InnoDB;